"""Generate JSON Schema and TS memory contracts from Pydantic, no parallel handwritten schema."""
import json
from pathlib import Path
from services.api.app.contracts import memory

MODELS = (memory.MemoryCandidateCreate, memory.MemoryConfirm, memory.MemoryRevoke,
          memory.MemoryConsentChange, memory.ConversationMemoryChange, memory.MemorySettingsResponse,
          memory.MemoryListResponse, memory.MemoryReference, memory.ConversationMemoryResponse,
          memory.ReportMemorySourcesResponse)


def ts_type(schema):
    if '$ref' in schema:
        return schema['$ref'].split('/')[-1]
    if 'const' in schema:
        return json.dumps(schema['const'])
    if 'enum' in schema:
        return ' | '.join(json.dumps(item) for item in schema['enum'])
    if 'anyOf' in schema:
        return ' | '.join(ts_type(item) for item in schema['anyOf'])
    if schema.get('type') == 'array':
        return f"Array<{ts_type(schema['items'])}>"
    return {'string': 'string', 'integer': 'number', 'number': 'number', 'boolean': 'boolean', 'null': 'null'}.get(schema.get('type'), 'unknown')


def main():
    root = Path(__file__).resolve().parents[1]
    schemas, definitions = {}, {}
    for model in MODELS:
        schema = model.model_json_schema()
        schemas[model.__name__] = schema
        definitions.update(schema.get('$defs', {}))
        definitions[model.__name__] = schema
    (root / 'contracts/memory.schema.json').write_text(json.dumps(schemas, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    lines = ['// Generated by scripts/export_memory_contracts.py. Do not edit.']
    for name, schema in definitions.items():
        lines.append(f'export type {name} = {{')
        for key, prop in schema.get('properties', {}).items():
            lines.append(f'  {key}{"" if key in schema.get("required", []) else "?"}: {ts_type(prop)};')
        lines.append('};')
    (root / 'apps/web/src/api/generated/memory.ts').write_text('\n'.join(lines)+'\n', encoding='utf-8')
    print('Generated memory contracts')


if __name__ == '__main__':
    main()
