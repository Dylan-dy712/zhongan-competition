"""Generate account JSON Schema and frontend types from executable Pydantic contracts."""
import json
from pathlib import Path
from services.api.app.accounts import SessionResponse, ConsentResponse, ProfileResponse


def ts_type(schema):
    if '$ref' in schema:return schema['$ref'].split('/')[-1]
    if 'const' in schema:return json.dumps(schema['const'])
    if 'enum' in schema:return ' | '.join(json.dumps(value) for value in schema['enum'])
    if 'anyOf' in schema:return ' | '.join(ts_type(value) for value in schema['anyOf'])
    return {'string':'string','integer':'number','number':'number','boolean':'boolean','null':'null'}.get(schema.get('type'),'unknown')


def main():
    root=Path(__file__).resolve().parents[1]
    definitions={};schemas={}
    for model in (SessionResponse,ConsentResponse,ProfileResponse):
        schema=model.model_json_schema();schemas[model.__name__]=schema
        definitions.update(schema.get('$defs',{}));definitions[model.__name__]=schema
    target=root/'contracts/accounts.schema.json'
    target.write_text(json.dumps(schemas,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    lines=['// Generated by scripts/export_account_contracts.py. Do not edit.']
    for name,schema in definitions.items():
        lines.append(f'export type {name} = {{')
        required=schema.get('required',[])
        for key,value in schema.get('properties',{}).items():
            lines.append(f'  {key}{"" if key in required else "?"}: {ts_type(value)};')
        lines.append('};')
    output=root/'apps/web/src/api/generated/accounts.ts';output.parent.mkdir(parents=True,exist_ok=True)
    output.write_text('\n'.join(lines)+'\n',encoding='utf-8')
    print('Generated account contracts')


if __name__=='__main__':main()
