def classify_disease_group(facts) -> dict | None:
    """按（出院/任一）诊断文本关键词匹配病种组；无匹配返回 None。"""
    import sys
    from pathlib import Path

    sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
    dx_texts = [d.name.value or "" for d in facts.diagnoses]
    proc_texts = [p.name.value or "" for p in facts.procedures]
    corpus = "；".join(dx_texts + proc_texts)
    best = None
    for g in GROUPS:
        score = sum(len(re.findall(k, corpus)) for k in g["dx_keywords"])
        if score > 0 and (best is None or score > best[1]):
            best = (g, score)
    return best[0] if best else None
